/**
 * Emits the staging DDL for every manifest table.
 *
 * The SQL is written into the custom migration once and committed; this script
 * exists so the file can be regenerated and so a test can assert the committed
 * migration still matches the manifest and the legacy schema contract.
 *
 * Usage:
 *   node --import tsx scripts/import/ddl.ts          # print to stdout
 *   node --import tsx scripts/import/ddl.ts --write  # write into the migration
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import legacy from './legacy-schema.json' with { type: 'json' }
import { ALL_TABLES, SKIPPED_DATED_DUPLICATES, stagingTable } from './manifest'

const here = dirname(fileURLToPath(import.meta.url))
// 0016 created the first 98 staging tables; 0017 is the idempotent expansion
// once the manifest classified the rest of the legacy schema (CREATE ... IF NOT
// EXISTS makes it safe to re-emit every table).
const migrationFile = join(here, '../../packages/db/drizzle/0017_migration_staging_expand.sql')

export function stagingDdl(): string {
  const tables = (legacy as { tables: Record<string, { columns: { name: string }[] }> }).tables
  const statements: string[] = [
    '-- Generated by scripts/import/ddl.ts from scripts/import/manifest.ts and',
    '-- the legacy schema contract. Do not edit by hand: run `pnpm migration:ddl --write`.',
    '--',
    '-- Every staging column is text on purpose: a bad legacy value must land and be',
    '-- reported, never coerced or rejected at load time.',
    '',
  ]

  for (const entry of ALL_TABLES) {
    const definition = tables[entry.table]
    if (!definition) throw new Error(`unknown legacy table ${entry.table}`)
    const columns = definition.columns
      .map((column) => `  "${column.name}" text`)
      .join(',\n')
    statements.push(
      `CREATE TABLE IF NOT EXISTS "migration"."${stagingTable(entry.table)}" (`,
      '  "_row_no" integer NOT NULL,',
      '  "_source_pk" text NOT NULL,',
      '  "_row_hash" text NOT NULL,',
      '  "_dump_id" text NOT NULL,',
      '  "_loaded_at" timestamptz NOT NULL DEFAULT now(),',
      columns ? `${columns},` : '',
      '  PRIMARY KEY ("_dump_id", "_row_no")',
      ');',
      `CREATE INDEX IF NOT EXISTS "${stagingTable(entry.table)}_pk_idx" ON "migration"."${stagingTable(entry.table)}" ("_source_pk");`,
      '',
    )
  }

  statements.push('-- Tables classified as dated/duplicate copies are never staged.')
  for (const table of SKIPPED_DATED_DUPLICATES) {
    statements.push(`-- skipped: ${table}`)
  }
  statements.push('')

  return statements.join('\n')
}

export function writeStagingDdl(): void {
  writeFileSync(migrationFile, stagingDdl())
}

// Only the direct invocation prints or writes; importing this module for a test
// must have no side effects.
const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  if (process.argv.includes('--write')) {
    writeStagingDdl()
    console.log(`wrote ${migrationFile}`)
  } else {
    process.stdout.write(stagingDdl())
  }
}

// Keep the read import honest for the test that compares the committed file.
export function committedStagingDdl(): string {
  return readFileSync(migrationFile, 'utf8')
}
